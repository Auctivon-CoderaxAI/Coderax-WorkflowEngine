export function readmeSource(blueprint: GameBlueprint, spec: GameSpec, buildId: string): string {
  const mechanics = blueprint.mechanics.map((mechanic) => `- \`${mechanic}\``).join('\n');
  const controls = blueprint.controls.map((control) => `- **${control.action}** — ${control.keys}`).join('\n');
  return `# Generated game: ${spec.prompt.slice(0, 90)}

Built by Coderax Native Game Studio (build \`${buildId}\`).

## Specification

- Genre: \`${spec.genre}\`
- Camera: \`${spec.camera}\`
- Difficulty: ${spec.difficulty}/5
- Levels: ${spec.levels}

${spec.prompt}

## Mechanics in this build

${mechanics}

## Controls

${controls}
- **pause** — P
- **restart level** — R

## How it works

\`src/game.js\` is the complete rule set: fixed-step movement, axis-separated AABB
collision, hazards, scoring, objectives and level completion. \`src/render.js\`
draws that state and nothing else. The same \`src/game.js\` is executed by the
studio's verification sandbox, so the verified build and the playable build
cannot diverge.

## Assets, audio and licence

Every sprite, tile, palette and level in this project was generated for it. No
third-party asset, trademark, character or sound is included. The generated
theme backdrop is \`assets/theme.svg\`; sound cues are synthesized at runtime by
\`src/audio.js\` with the Web Audio API, and no audio file is shipped.
\`index.html\` inlines the generated modules so the preview is one self-contained
document; the same modules are present in \`src/\` as readable source. Provenance
is recorded in \`manifest.json\`; the whole project is exportable as a ZIP archive.

## Verification

A build is only listed as verified after the studio's deterministic bot finishes
every level and the scripted collision, scoring, input and mechanics checks pass.
Open the engine's game capability report for the measured evidence of this
deployment.
`;
}

