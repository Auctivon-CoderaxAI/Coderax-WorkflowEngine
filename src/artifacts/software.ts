import { execFile } from 'node:child_process';
import { createRequire } from 'node:module';
import { promisify } from 'node:util';
import type { SoftwareRequest, SourceFile, VerificationCheck } from '@coderax/contracts';
import { resolveInside, writeArtifact } from './file.js';

const execFileAsync = promisify(execFile);
const require = createRequire(import.meta.url);

/**
 * Software deliverables are a source tree plus an objective check of that tree.
 *
 * Verification parses every source file (Node's `--check` compiles without
 * executing) and resolves every relative import to a file that exists. It does
 * not run the generated program: the engine has no sandbox that could contain
 * arbitrary code, and claiming "tested" without one would be a false claim. The
 * check reports exactly what it proved.
 */

export type SoftwareBuild = {
  folder: string;
  entry: string;
  /** Paths are relative to the staging root, never to a user workspace. */
  files: Array<{ path: string; bytes: number; sha256: string }>;
  checks: VerificationCheck[];
};

function packageJson(input: { request: SoftwareRequest; typeModule: boolean; entry: string }): string {
  return `${JSON.stringify(
    {
      name: input.request.name,
      version: '0.1.0',
      private: true,
      ...(input.typeModule ? { type: 'module' } : {}),
      description: input.request.description,
      scripts: {
        start: `node ${input.entry}`,
        test: `node --test test/*.test.${input.entry.endsWith('.ts') ? 'ts' : 'js'}`,
      },
    },
    null,
    2,
  )}\n`;
}

function readme(request: SoftwareRequest, entry: string): string {
  return `# ${request.name}

${request.description}

## Run

\`\`\`bash
npm start
\`\`\`

Entry point: \`${entry}\`.

## Verify

\`\`\`bash
node --check ${entry}
node --test test/*.test.js
\`\`\`

Generated by Coderax WorkflowEngine. Verification compiled each file without
executing it; run the project locally to exercise its behaviour.
`;
}

function moduleTemplate(request: SoftwareRequest): SourceFile[] {
  const typescript = request.language === 'typescript';
  const extension = typescript ? 'ts' : 'js';
  const annotation = typescript ? ': { ok: boolean; project: string; input: unknown }' : '';
  const parameter = typescript ? 'input: unknown = null' : 'input = null';
  return [
    { path: 'package.json', content: packageJson({ request, typeModule: true, entry: `src/index.${extension}` }) },
    {
      path: `src/index.${extension}`,
      content: `/**
 * ${request.description}
 */
export function run(${parameter})${annotation} {
  return { ok: true, project: '${request.name}', input };
}
`,
    },
    {
      path: `test/index.test.${extension}`,
      content: `import test from 'node:test';
import assert from 'node:assert/strict';
import { run } from '../src/index.${extension}';

test('run reports success for the scaffold', () => {
  const result = run({ sample: true });
  assert.equal(result.ok, true);
  assert.equal(result.project, '${request.name}');
});
`,
    },
    { path: 'README.md', content: readme(request, `src/index.${extension}`) },
  ];
}

function cliTemplate(request: SoftwareRequest): SourceFile[] {
  const typescript = request.language === 'typescript';
  const extension = typescript ? 'ts' : 'js';
  const description = JSON.stringify(request.description);
  return [
    { path: 'package.json', content: packageJson({ request, typeModule: true, entry: `src/index.${extension}` }) },
    {
      path: `src/index.${extension}`,
      content: `#!/usr/bin/env node
import { pathToFileURL } from 'node:url';
/**
 * ${request.description.replace(/\*\//g, '* /')}
 */
export function parseArguments(argv${typescript ? ': string[]' : ''})${typescript ? ': { help: boolean; values: string[] }' : ''} {
  const values = argv.filter((value) => !value.startsWith('-'));
  return { help: argv.includes('--help') || argv.includes('-h'), values };
}

function main() {
  const args = parseArguments(process.argv.slice(2));
  if (args.help) {
    console.log('Usage: ${request.name} [arguments]');
    console.log(${description});
  } else {
    console.log(JSON.stringify({ project: '${request.name}', arguments: args.values }));
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
`,
    },
    {
      path: `test/index.test.${extension}`,
      content: `import test from 'node:test';
import assert from 'node:assert/strict';
import { parseArguments } from '../src/index.${extension}';

test('parseArguments separates flags from values', () => {
  const result = parseArguments(['--help', 'alpha']);
  assert.equal(result.help, true);
  assert.deepEqual(result.values, ['alpha']);
});
`,
    },
    { path: 'README.md', content: readme(request, `src/index.${extension}`) },
  ];
}

function serviceTemplate(request: SoftwareRequest): SourceFile[] {
  const typescript = request.language === 'typescript';
  const extension = typescript ? 'ts' : 'js';
  const requestType = typescript
    ? 'import type { IncomingMessage, ServerResponse } from "node:http";\n'
    : '';
  const types = typescript
    ? ': { status: number; body: { ok: boolean; service: string } }'
    : '';
  const handlerTypes = typescript
    ? 'request: IncomingMessage, response: ServerResponse'
    : 'request, response';
  return [
    { path: 'package.json', content: packageJson({ request, typeModule: true, entry: `src/index.${extension}` }) },
    {
      path: `src/index.${extension}`,
      content: `${requestType}import { createServer } from 'node:http';
import { pathToFileURL } from 'node:url';
/**
 * ${request.description.replace(/\*\//g, '* /')}
 */
export function health${types}() {
  return { status: 200, body: { ok: true, service: '${request.name}' } };
}

export function handler(${handlerTypes}) {
  if (request.url === '/health') {
    const result = health();
    response.writeHead(result.status, { 'content-type': 'application/json; charset=utf-8' });
    response.end(JSON.stringify(result.body));
    return;
  }
  response.writeHead(404, { 'content-type': 'application/json; charset=utf-8' });
  response.end(JSON.stringify({ ok: false }));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const port = Number(process.env.PORT ?? 8080);
  createServer(handler).listen(port, '127.0.0.1', () => {
    console.log(\`${request.name} listening on \${port}\`);
  });
}
`,
    },
    {
      path: `test/health.test.${extension}`,
      content: `import test from 'node:test';
import assert from 'node:assert/strict';
import { health } from '../src/index.${extension}';

test('health reports the service identity', () => {
  const result = health();
  assert.equal(result.status, 200);
  assert.equal(result.body.service, '${request.name}');
});
`,
    },
    { path: 'README.md', content: readme(request, `src/index.${extension}`) },
  ];
}

export function templateFiles(request: SoftwareRequest): SourceFile[] {
  if (request.template === 'module') return moduleTemplate(request);
  if (request.template === 'cli') return cliTemplate(request);
  if (request.template === 'service') return serviceTemplate(request);
  return [];
}

function importSpecifiers(content: string): string[] {
  const specifiers: string[] = [];
  for (const match of content.matchAll(/(?:from\s+|import\s*\(\s*)['"]([^'"]+)['"]/g)) {
    if (match[1]) specifiers.push(match[1]);
  }
  return specifiers;
}

function resolvesWithin(files: Set<string>, from: string, specifier: string): boolean {
  const base = from.includes('/') ? from.slice(0, from.lastIndexOf('/')) : '';
  const segments = `${base}/${specifier}`.split('/');
  const resolved: string[] = [];
  for (const segment of segments) {
    if (segment === '..') resolved.pop();
    else if (segment !== '.' && segment.length > 0) resolved.push(segment);
  }
  const target = resolved.join('/');
  return (
    files.has(target) ||
    files.has(`${target}.js`) ||
    files.has(`${target}.mjs`) ||
    files.has(`${target}.ts`) ||
    files.has(`${target}/index.js`) ||
    files.has(`${target}/index.ts`)
  );
}

function stripProjectPath(text: string, root: string): string {
  return text.split(root).join('').replace(/\s+/g, ' ').trim().slice(0, 180);
}

async function syntaxCheck(input: {
  absolutePath: string;
  relativePath: string;
  root: string;
}): Promise<VerificationCheck> {
  try {
    await execFileAsync(process.execPath, ['--check', input.absolutePath], {
      cwd: input.root,
      timeout: 10_000,
      windowsHide: true,
    });
    return { name: `syntax:${input.relativePath}`, ok: true, detail: 'Parsed by Node without executing.' };
  } catch (error) {
    const stderr = (error as { stderr?: string }).stderr ?? '';
    return {
      name: `syntax:${input.relativePath}`,
      ok: false,
      detail: stripProjectPath(stderr, input.root) || 'Node reported a syntax error.',
    };
  }
}

function typescriptCheck(input: { relativePath: string; content: string }): VerificationCheck {
  let compiler: typeof import('typescript');
  try {
    compiler = require('typescript') as typeof import('typescript');
  } catch {
    return {
      name: `syntax:${input.relativePath}`,
      ok: false,
      detail:
        'TypeScript verification needs the TypeScript compiler in the execution image; it is not installed.',
    };
  }
  const result = compiler.transpileModule(input.content, {
    fileName: input.relativePath,
    reportDiagnostics: true,
    compilerOptions: {
      target: compiler.ScriptTarget.ES2022,
      module: compiler.ModuleKind.ESNext,
      strict: true,
    },
  });
  const errors = (result.diagnostics ?? []).filter(
    (diagnostic) => diagnostic.category === compiler.DiagnosticCategory.Error,
  );
  if (errors.length === 0) {
    return {
      name: `syntax:${input.relativePath}`,
      ok: true,
      detail: 'Parsed by the TypeScript compiler without emitting or executing.',
    };
  }
  const first = errors[0]!;
  const message = compiler.flattenDiagnosticMessageText(first.messageText, ' ');
  return {
    name: `syntax:${input.relativePath}`,
    ok: false,
    detail: `TypeScript reported: ${message.slice(0, 180)}`,
  };
}

export async function buildSoftware(input: {
  request: SoftwareRequest;
  root: string;
  folder: string;
}): Promise<SoftwareBuild> {
  const generated = templateFiles(input.request);
  const files = input.request.files.length > 0 ? input.request.files : generated;
  if (files.length === 0) {
    throw new RangeError('A software deliverable needs files or a template.');
  }
  const entry =
    input.request.entry ??
    files.find((file) => /^src\/index\.(js|ts)$/.test(file.path))?.path ??
    files[0]!.path;
  if (!files.some((file) => file.path === entry)) {
    throw new RangeError('The declared entry point is not one of the delivered files.');
  }

  const written: SoftwareBuild['files'] = [];
  for (const file of files) {
    resolveInside(input.root, `${input.folder}/${file.path}`);
    const artifact = await writeArtifact({
      root: input.root,
      relative: `${input.folder}/${file.path}`,
      data: file.content,
    });
    written.push({ path: `${input.folder}/${file.path}`, bytes: artifact.bytes, sha256: artifact.sha256 });
  }

  const names = new Set(files.map((file) => file.path));
  const checks: VerificationCheck[] = [
    {
      name: 'entry',
      ok: names.has(entry),
      detail: `Entry point ${entry} is part of the delivered tree.`,
    },
  ];

  for (const file of files) {
    if (file.path.endsWith('.js') || file.path.endsWith('.mjs') || file.path.endsWith('.cjs')) {
      checks.push(
        await syntaxCheck({
          absolutePath: resolveInside(input.root, `${input.folder}/${file.path}`),
          relativePath: file.path,
          root: input.root,
        }),
      );
    } else if (file.path.endsWith('.ts')) {
      checks.push(typescriptCheck({ relativePath: file.path, content: file.content }));
    }
  }

  const packageFile = files.find((file) => file.path === 'package.json');
  if (packageFile) {
    let ok = true;
    let detail = 'package.json parsed.';
    try {
      JSON.parse(packageFile.content);
    } catch {
      ok = false;
      detail = 'package.json is not valid JSON.';
    }
    checks.push({ name: 'package.json', ok, detail });
  }

  for (const file of files) {
    if (!/\.(js|mjs|ts)$/.test(file.path)) continue;
    const missing = importSpecifiers(file.content)
      .filter((specifier) => specifier.startsWith('.'))
      .filter((specifier) => !resolvesWithin(names, file.path, specifier));
    checks.push({
      name: `imports:${file.path}`,
      ok: missing.length === 0,
      detail:
        missing.length === 0
          ? 'Every relative import resolves inside the delivered tree.'
          : `Unresolved relative imports: ${missing.join(', ')}.`,
    });
  }

  return { folder: input.folder, entry: `${input.folder}/${entry}`, files: written, checks };
}
