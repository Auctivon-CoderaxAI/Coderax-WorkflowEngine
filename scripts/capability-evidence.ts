import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { CONTRACT_VERSION, ROUTES } from '@coderax/contracts';

type TestLine = { ok: boolean; skipped: boolean; name: string };

function run(command: string, args: string[]): { status: number; stdout: string; stderr: string } {
  const result = spawnSync(command, args, {
    encoding: 'utf8',
    env: process.env,
    maxBuffer: 32 * 1024 * 1024,
  });
  return {
    status: result.status ?? 1,
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? '',
  };
}

function parseTap(output: string): {
  tests: number;
  pass: number;
  fail: number;
  skipped: number;
  topLevel: TestLine[];
} {
  const counts: Record<string, number> = {};
  const topLevel: TestLine[] = [];
  for (const line of output.split(/\r?\n/)) {
    const summary = /^#\s+(tests|pass|fail|skipped)\s+(\d+)$/.exec(line);
    if (summary) {
      counts[summary[1]!] = Number(summary[2]);
      continue;
    }
    const match = /^(ok|not ok)\s+\d+\s+-\s+(.+)$/.exec(line);
    if (match) {
      topLevel.push({
        ok: match[1] === 'ok',
        skipped: /#\s*(SKIP|TODO)\b/i.test(line),
        name: match[2]!.trim(),
      });
    }
  }
  return {
    tests: counts.tests ?? 0,
    pass: counts.pass ?? 0,
    fail: counts.fail ?? 0,
    skipped: counts.skipped ?? 0,
    topLevel,
  };
}

function git(args: string[]): string {
  const result = spawnSync('git', args, { encoding: 'utf8' });
  return result.status === 0 ? (result.stdout ?? '').trim() : 'unknown';
}

const testRun = run(process.execPath, [
  '--test',
  '--test-reporter=tap',
  'dist/tests/**/*.test.js',
]);
const parsed = parseTap(testRun.stdout);
const openapi = run(process.execPath, ['dist/scripts/check-openapi.js']);
const commit = git(['rev-parse', '--short=12', 'HEAD']);
const branch = git(['rev-parse', '--abbrev-ref', 'HEAD']);
const generatedAt = new Date().toISOString();
const mongoEnabled = Boolean(process.env['CODERAX_TEST_MONGODB_URI']);
const mongoTest = parsed.topLevel.find((entry) =>
  /survive a restart/i.test(entry.name),
);

const lines: string[] = [
  '# Capability evidence',
  '',
  'Generated by `npm run evidence`. It reads the live route catalogue and the',
  'actual Node test result; it is not a hand-written claims table.',
  '',
  `- Generated: ${generatedAt}`,
  `- Commit: \`${commit}\` on \`${branch}\``,
  `- Node: ${process.version}`,
  `- Contract version: \`${CONTRACT_VERSION}\``,
  `- HTTP operations in the catalogue: ${ROUTES.length}`,
  `- Tests: ${parsed.pass} passed, ${parsed.fail} failed, ${parsed.skipped} skipped (${parsed.tests} total)`,
  `- OpenAPI drift check: ${openapi.status === 0 ? 'clean' : 'FAILED'}`,
  `- Live MongoDB evidence: ${
    mongoEnabled && mongoTest?.ok && !mongoTest.skipped
      ? 'the restart suite passed against a real mongod'
      : mongoEnabled && mongoTest
        ? 'the restart suite FAILED or was skipped'
        : 'not run; set CODERAX_TEST_MONGODB_URI and rerun `npm run test:mongo`'
  }`,
  '',
  '## Test results',
  '',
  ...(parsed.topLevel.length > 0
    ? parsed.topLevel.map(
        (entry) =>
          `- [${entry.ok && !entry.skipped ? 'x' : ' '}] ${entry.name}${
            entry.skipped ? ' (skipped)' : ''
          }`,
      )
    : ['- No test output was produced.']),
  '',
  '## HTTP operations',
  '',
  '| Method | Path | Operation |',
  '| --- | --- | --- |',
  ...ROUTES.map(
    (route) => `| ${route.method} | \`${route.path}\` | \`${route.operationId}\` |`,
  ),
  '',
  '## What this evidence does not claim',
  '',
  '- Coderax Web and CoderaxCLI have not been migrated onto this API.',
  '- The engine has not been deployed to a cloud environment.',
  '- OpenCode and FreeBuff transports are not live-verified; an unavailable',
  '  external agent is refused rather than replaced.',
  '- The live MongoDB suite is production persistence evidence only when the line',
  '  above says it passed; the in-memory suite alone is not.',
  '',
];

const output = path.join(process.cwd(), 'docs', 'capability-evidence.md');
writeFileSync(output, lines.join('\n'), 'utf8');

process.stdout.write(
  `wrote ${path.relative(process.cwd(), output)}: ${parsed.pass} passed, ` +
    `${parsed.fail} failed, ${parsed.skipped} skipped\n`,
);

if (testRun.status !== 0 || openapi.status !== 0) {
  if (testRun.status !== 0) process.stderr.write(testRun.stderr);
  if (openapi.status !== 0) process.stderr.write(openapi.stderr);
  process.exit(1);
}
